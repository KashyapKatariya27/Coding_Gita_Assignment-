console.log(true > false);
// true
// true = 1 and false = 0
// 1 > 0 => true

console.log("10" > "2");
// false
// Both are strings, so JavaScript compares them lexicographically.
// "1" comes before "2", therefore "10" > "2" is false.

console.log(NaN > 5);
// false
// Any comparison using NaN with > returns false.