console.log("10" > "2"); // false
console.log(10 > 2);     // true

// Explanation:
//
// "10" > "2"
// Both values are strings.
// JavaScript compares them lexicographically.
// First characters are compared: "1" > "2" => false
//
// 10 > 2
// Both values are numbers.
// JavaScript performs numeric comparison.
// 10 > 2 => true